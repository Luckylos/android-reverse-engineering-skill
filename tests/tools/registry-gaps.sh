#!/usr/bin/env bash
# tests/tools/registry-gaps.sh -- dev-only generator of the computed part of
# skills/sdk-neutralizer/references/registry-backlog.md (DESIGN 3.4, 7). Not shipped
# with the plugin (lives under tests/); needs jq >= 1.6.
#
# Usage: tests/tools/registry-gaps.sh [--check | --write] [--registry DIR] [--file F]
#   (no mode)   print the generated block (markers included) on stdout
#   --check     exit 0 when the block between the markers of F equals the generated
#               one, 1 (with a diff) when it is stale, 2 when F or its markers are missing
#   --write     replace the block between the markers of F with the generated one
#   --registry  registry directory (default: the plugin's sdk-neutralizer/registry)
#   --file      backlog file (default: the plugin's sdk-neutralizer/references/registry-backlog.md)
#
# The block lists, for every registry entry, the gaps that can be computed from the
# registry itself (the rest of the backlog is written by hand):
#   DO  detection-only entry: no `targets` (registry-scan.py skips it)
#   P   a `detection` root that no `packages` item covers (equal or above it):
#       extra_packages (identity), namespace_roots, adapter_packages
#   A   a `detection.apis` method that is neither an entry point nor an ad operation
#       of `targets` (same class and method name)
# Rows: group order ads, trackers, consent (category_groups of _audit-shared.json),
# then sdk_id in byte order; one row per (entry, gap type) in the order DO, P, A.
set -euo pipefail
export LC_ALL=C

here=$(cd "$(dirname "$0")" && pwd)
REPO=$(cd "$here/../.." && pwd)
PL=${ARE_PLUGIN:-$REPO/plugins/android-reverse-engineering}
REGDIR=$PL/skills/sdk-neutralizer/registry
FILE=$PL/skills/sdk-neutralizer/references/registry-backlog.md
MODE=print
BEGIN_MARK='<!-- BEGIN registry-gaps: generated by tests/tools/registry-gaps.sh, do not edit by hand -->'
END_MARK='<!-- END registry-gaps -->'

usage() { sed -n '2,23p' "$0" | sed 's/^# \{0,1\}//'; }
while [ $# -gt 0 ]; do
  case "$1" in
    --check) MODE=check ;;
    --write) MODE=write ;;
    --registry) [ $# -ge 2 ] || { usage >&2; exit 2; }; REGDIR=$2; shift ;;
    --file) [ $# -ge 2 ] || { usage >&2; exit 2; }; FILE=$2; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "registry-gaps: unknown option $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

command -v jq >/dev/null 2>&1 || { echo "registry-gaps: jq not found" >&2; exit 2; }
[ "$(jq -nr '[limit(1;1,2)] | IN(.[]; 1) | tostring' 2>/dev/null)" = true ] ||
  { echo "registry-gaps: jq >= 1.6 required" >&2; exit 2; }
[ -f "$REGDIR/_audit-shared.json" ] || { echo "registry-gaps: $REGDIR/_audit-shared.json not found" >&2; exit 2; }

generate() {
  # entry files in byte order (LC_ALL=C glob), _* files excluded
  set -- "$REGDIR"/[!_]*.json
  [ -f "$1" ] || { echo "registry-gaps: no registry entries in $REGDIR" >&2; return 2; }
  jq -n -r --slurpfile shared "$REGDIR/_audit-shared.json" '
      def covered($p; $pkgs): any($pkgs[]; . as $q | $q == $p or ($p | startswith($q + ".")));
      def simple: split(".") | last;
      def code: "`" + . + "`";
      ($shared[0].category_groups) as $cg
      | ["ads", "trackers", "consent"] as $order
      | [inputs] as $entries
      | [ $entries[]
          | . as $e
          | ($cg | to_entries | map(select(.value | index($e.category))) | .[0].key // "other") as $g
          | (($e.packages // []) | map(select(type == "string"))) as $pkgs
          | ($e.detection // {}) as $d
          | {group: $g, rank: (($order | index($g)) // 9), id: $e.sdk_id,
             name: ($e.display_name // $e.sdk_id), cat: $e.category,
             do: ($e | has("targets") | not),
             pkgs: $pkgs,
             p: [ [ ["extra", ($d.extra_packages // [])], ["namespace", ($d.namespace_roots // [])],
                    ["adapter", ($d.adapter_packages // [])] ][]
                  | .[0] as $k | [.[1][] | select(covered(.; $pkgs) | not)]
                  | select(length > 0) | "\($k): " + (map(code) | join(", ")) ],
             a: (([ ($e.targets // {}) | (.entry_points // [], .ad_operations // [])[]
                   | .class as $c | (.methods // [])[] | "\($c)#\(.name)" ] ) as $tm
                | [ ($d.apis // [])[] | .class as $c | .role as $r
                    | [ .methods[] | select(("\($c)#\(.)" | IN($tm[])) | not) ] as $ms
                    | select($ms | length > 0)
                    | "`\($c | simple)#\($ms | join(","))` (\($r))" ]) }
        ]
      | sort_by(.rank, .id)
      | ( "| Group | SDK | sdk_id | Gap | Items |",
          "|---|---|---|---|---|",
          ( .[]
            | . as $r
            | ( if $r.do then "| \($r.group) | \($r.name) | `\($r.id)` | DO | no targets; packages " + ($r.pkgs | map(code) | join(", ")) + " |" else empty end ),
              ( if ($r.p | length) > 0 then "| \($r.group) | \($r.name) | `\($r.id)` | P | " + ($r.p | join("; ")) + " |" else empty end ),
              ( if ($r.a | length) > 0 then "| \($r.group) | \($r.name) | `\($r.id)` | A | " + ($r.a | join("; ")) + " |" else empty end ) ),
          "",
          ( "Entries: \(length); detection-only (DO): \(map(select(.do)) | length); with P gaps: \(map(select(.p | length > 0)) | length); with A gaps: \(map(select(.a | length > 0)) | length)." ) )
    ' "$@"
}

block() {
  echo "$BEGIN_MARK"
  echo
  generate
  echo
  echo "$END_MARK"
}

# extract_block <file>: the marker block of the file (markers included)
extract_block() {
  awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
    $0 == b { on = 1; nb++ }
    on { print }
    $0 == e && on { on = 0; ne++ }
    END { if (nb != 1 || ne != 1) exit 3 }' "$1"
}

case "$MODE" in
  print)
    block ;;
  check)
    [ -f "$FILE" ] || { echo "registry-gaps: $FILE not found" >&2; exit 2; }
    tmp=$(mktemp -d "${TMPDIR:-/tmp}/registry-gaps.XXXXXX")
    trap 'rm -rf "$tmp"' EXIT
    extract_block "$FILE" >"$tmp/have" || { echo "registry-gaps: markers missing or repeated in $FILE" >&2; exit 2; }
    block >"$tmp/want"
    if cmp -s "$tmp/want" "$tmp/have"; then
      echo "registry-gaps: $FILE is up to date"
      exit 0
    fi
    echo "registry-gaps: $FILE is stale (run: bash tests/tools/registry-gaps.sh --write)"
    diff -u "$tmp/have" "$tmp/want" | sed 's/^/  /' | head -60
    exit 1 ;;
  write)
    [ -f "$FILE" ] || { echo "registry-gaps: $FILE not found" >&2; exit 2; }
    tmp=$(mktemp -d "${TMPDIR:-/tmp}/registry-gaps.XXXXXX")
    trap 'rm -rf "$tmp"' EXIT
    extract_block "$FILE" >/dev/null || { echo "registry-gaps: markers missing or repeated in $FILE" >&2; exit 2; }
    block >"$tmp/want"
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" -v nf="$tmp/want" '
      $0 == b { while ((getline l < nf) > 0) print l; skip = 1; next }
      skip && $0 == e { skip = 0; next }
      !skip { print }' "$FILE" >"$tmp/new"
    if cmp -s "$tmp/new" "$FILE"; then echo "registry-gaps: $FILE already up to date"; exit 0; fi
    cat "$tmp/new" >"$FILE"
    echo "registry-gaps: $FILE updated" ;;
esac
